async function init() {
  const sql = getSql();
  await sql.unsafe(SCHEMA);

  // Demo accounts: added if missing, on new and existing databases.
  for (const [employeeId, name, password, role] of DEMO_USERS) {
    const [exists] = await sql`SELECT 1 FROM users WHERE employee_id = ${employeeId}`;
    if (!exists) {
      await sql`INSERT INTO users (employee_id, name, password_hash, role)
                VALUES (${employeeId}, ${name}, ${bcrypt.hashSync(password, 10)}, ${role})`;
    }
  }
  // Clients (consignors) are real data, managed in Vehicles & Clients — no demo clients.
}

