import postgres from "postgres";
import bcrypt from "bcryptjs";
import { AsyncLocalStorage } from "node:async_hooks";

// Supabase Postgres (DATABASE_URL in .env.local — the SESSION pooler, port 5432: right for a
// long-running server; the transaction pooler (6543) stalls on concurrent queries here).
// The rest of the server keeps the old `db.prepare(sql).get/all/run` style; the
// calls are now async (`await db.prepare(...).get(...)`) and `?` placeholders
// still work.

if (!process.env.DATABASE_URL) {
  throw new Error("DATABASE_URL is missing — add the Supabase connection string to .env.local");
}

// One client per server process (Next dev reloads modules; don't leak connections).
export const sql =
  globalThis.__pgClient ??
  (globalThis.__pgClient = postgres(process.env.DATABASE_URL, {
    prepare: false, // also safe if DATABASE_URL ever points at the transaction pooler
    onnotice: () => {}, // silence "already exists, skipping" from CREATE IF NOT EXISTS
    max: 5,
    idle_timeout: 20,
    // COUNT(*) etc. come back as bigint; the app expects plain numbers.
    types: { bigint: { to: 20, from: [20], parse: (v) => Number(v), serialize: (v) => String(v) } },
  }));

// Statements inside withTransaction() run on the transaction's connection.
const txStore = new AsyncLocalStorage();
const conn = () => txStore.getStore() ?? sql;

const toPg = (text) => {
  let n = 0;
  return text.replace(/\?/g, () => `$${++n}`);
};

// Schema + demo seed run once, lazily, before the first query (so the
// sqlite-to-supabase import script can load data first without seeding).
const ensureReady = () =>
  (globalThis.__pgReady ??= init().catch((err) => {
    globalThis.__pgReady = undefined; // retry on the next request
    throw err;
  }));

function prepare(text) {
  const query = toPg(text);
  const exec = async (params) => {
    await ensureReady();
    return conn().unsafe(query, params);
  };
  return {
    get: async (...params) => (await exec(params))[0],
    all: async (...params) => [...(await exec(params))],
    run: async (...params) => {
      // Mirror SQLite's { changes, lastInsertRowid } for INSERTs.
      const isInsert = /^\s*insert/i.test(query) && !/returning/i.test(query);
      const rows = isInsert ? await (async () => {
        await ensureReady();
        return conn().unsafe(`${query} RETURNING id`, params);
      })() : await exec(params);
      return { changes: rows.count, lastInsertRowid: rows[0]?.id };
    },
  };
}

export const db = { prepare };

export async function withTransaction(fn) {
  await ensureReady();
  return sql.begin((tx) => txStore.run(tx, fn));
}

// Timestamps stay TEXT 'YYYY-MM-DD HH:MM:SS' in UTC — the format the screens already expect.
export const NOW = "to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')";
// "Today" for business counts is Indian time.
export const TODAY_IST = "(now() at time zone 'Asia/Kolkata')::date";
export const istDate = (col) => `((${col})::timestamp at time zone 'utc' at time zone 'Asia/Kolkata')::date`;

export const SCHEMA = `
CREATE TABLE IF NOT EXISTS users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id text UNIQUE NOT NULL,
  name text NOT NULL,
  password_hash text NOT NULL,
  role text NOT NULL DEFAULT 'dispatcher',
  created_at text NOT NULL DEFAULT ${NOW}
);
CREATE TABLE IF NOT EXISTS vehicles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehicle_no text UNIQUE NOT NULL,
  vehicle_type text,
  driver_name text,
  driver_phone text,
  affiliated_company text,
  capacity_kg double precision,
  status text NOT NULL DEFAULT 'Available',
  created_at text NOT NULL DEFAULT ${NOW}
);
CREATE TABLE IF NOT EXISTS clients (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text UNIQUE NOT NULL,
  gstin text,
  address text,
  payment_terms_days integer NOT NULL DEFAULT 21,
  gate_contact_name text,
  gate_contact_phone text,
  created_at text NOT NULL DEFAULT ${NOW}
);
CREATE TABLE IF NOT EXISTS lrs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lr_no text UNIQUE NOT NULL,
  lr_date text NOT NULL,
  consignor_name text NOT NULL,
  consignor_address text,
  consignee_name text NOT NULL,
  consignee_address text,
  vehicle_id integer REFERENCES vehicles(id),
  from_location text NOT NULL,
  to_location text NOT NULL,
  invoice_no text,
  delivery_at text,
  eway_bill_no text,
  freight_terms text NOT NULL DEFAULT 'To Pay',
  amount double precision NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'Draft',
  remarks text,
  created_by integer REFERENCES users(id),
  created_at text NOT NULL DEFAULT ${NOW},
  updated_at text NOT NULL DEFAULT ${NOW}
);
CREATE TABLE IF NOT EXISTS lr_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lr_id integer NOT NULL REFERENCES lrs(id) ON DELETE CASCADE,
  no_of_pkgs text,
  said_to_contain text,
  weight_kg text,
  rate_per_kg text,
  freight_amount text,
  remarks text,
  received_qty text,
  item_condition text,
  receiving_remarks text
);
CREATE TABLE IF NOT EXISTS lr_status_log (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lr_id integer NOT NULL REFERENCES lrs(id) ON DELETE CASCADE,
  status text NOT NULL,
  note text,
  changed_by integer REFERENCES users(id),
  changed_at text NOT NULL DEFAULT ${NOW}
);
CREATE INDEX IF NOT EXISTS lr_items_lr_id ON lr_items (lr_id);
CREATE INDEX IF NOT EXISTS lr_status_log_lr_id ON lr_status_log (lr_id);
-- Supabase exposes the public schema through its web API. RLS with no policies
-- blocks that completely; this server connects as the owner and isn't affected.
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE vehicles ENABLE ROW LEVEL SECURITY;
ALTER TABLE clients ENABLE ROW LEVEL SECURITY;
ALTER TABLE lrs ENABLE ROW LEVEL SECURITY;
ALTER TABLE lr_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE lr_status_log ENABLE ROW LEVEL SECURITY;
`;

